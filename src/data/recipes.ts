import type { Recipe } from '@/lib/recipes';
import { ingredientSlug } from '@/lib/recipes';
function recipe(
  id: string,
  title: string,
  description: string,
  category: string,
  mainIngredient: string,
  minutes: number,
  vegetarian: boolean,
  ingredients: [string, string][],
  steps: string[],
  featured = 99,
): Recipe {
  return {
    id: `nn-${id}`,
    title,
    description,
    category,
    mainIngredient,
    minutes,
    vegetarian,
    servings: 4,
    language: 'nn',
    featured,
    image: '',
    imageAlt: title,
    area: 'Kvardagsmat',
    ingredients: ingredients.map(([measure, name]) => ({
      measure,
      name,
      slug: ingredientSlug(name),
    })),
    steps,
    tags: [category, mainIngredient],
    source: null,
    youtube: null,
  };
}
